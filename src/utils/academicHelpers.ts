// Generate BibTeX string from paper sources or evidence matrix
export function generateBibTeX(papers: (PaperSource | EvidenceMatrixEntry)[]): string {
  return papers
    .map((paper, idx) => {
      const isMatrix = 'authorsFormatted' in paper;
      const title = isMatrix ? paper.paperTitle : paper.title;
      const year = paper.year || 2024;
      const venue = paper.venue || 'ArXiv';
      const doi = paper.doi ? `  doi       = {${paper.doi}},\n` : '';
      const rawAuthor = isMatrix
        ? (paper as EvidenceMatrixEntry).authorsFormatted.replace(/ et al\./g, ' and others')
        : (paper as PaperSource).authors.join(' and ');

      const firstAuthor = rawAuthor.split(' ')[0].replace(/[^a-zA-Z]/g, '').toLowerCase() || `source${idx + 1}`;
      const citeKey = `${firstAuthor}${year}${idx + 1}`;

      return `@article{${citeKey},
  author    = {${rawAuthor}},
  title     = {{${title}}},
  journal   = {${venue}},
  year      = {${year}},
${doi}  note      = {Verified scholarly source}
}`;
    })
    .join('\n\n');
}

// Generate LaTeX document
export function generateLaTeX(title: string, draftMarkdown: string, bibtex: string): string {
  // Simple markdown to latex converter for key headings
  const latexBody = draftMarkdown
    .replace(/^# (.*$)/gim, '\\title{$1}')
    .replace(/^## 12\. References[\s\S]*/im, '\\bibliographystyle{IEEEtran}\n\\bibliography{references}')
    .replace(/^## (.*$)/gim, '\\section{$1}')
    .replace(/^### (.*$)/gim, '\\subsection{$1}')
    .replace(/\*\*(.*?)\*\*/g, '\\textbf{$1}')
    .replace(/\*(.*?)\*/g, '\\textit{$1}');

  return `% Generated by ScholarForge AI Research Paper Agent
\\documentclass[10pt,journal,compsoc]{IEEEtran}
\\usepackage[utf8]{inputenc}
\\usepackage{amsmath,amssymb,amsfonts}
\\usepackage{graphicx}
\\usepackage{cite}
\\usepackage{hyperref}
\\usepackage{booktabs}

\\begin{document}

${latexBody}

\\end{document}
`;
}

// Generate CSV string for Evidence Matrix
export function generateEvidenceMatrixCSV(matrix: EvidenceMatrixEntry[]): string {
  const headers = [
    'Paper Title',
    'Authors',
    'Year',
    'Venue',
    'DOI',
    'Research Question',
    'Methodology',
    'Key Findings',
    'Limitations',
    'Relevance Score',
    'Relevance Rationale',
    'Evidence Type'
  ];

  const escapeCSV = (str: string | number | undefined) => {
    if (str === undefined || str === null) return '""';
    const clean = String(str).replace(/"/g, '""');
    return `"${clean}"`;
  };

  const rows = matrix.map(row => [
    escapeCSV(row.paperTitle),
    escapeCSV(row.authorsFormatted),
    escapeCSV(row.year),
    escapeCSV(row.venue),
    escapeCSV(row.doi || ''),
    escapeCSV(row.researchQuestion),
    escapeCSV(row.methodology),
    escapeCSV(row.keyFindings),
    escapeCSV(row.limitations),
    escapeCSV(row.relevanceScore),
    escapeCSV(row.relevanceRationale),
    escapeCSV(row.primaryEvidenceType)
  ].join(','));

  return [headers.join(','), ...rows].join('\n');
}

// Download helper
export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

